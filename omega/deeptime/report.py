"""Writes omega/reports/deep_time_tables.md: every number behind the deep-time report, from the JSON results."""
import json, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import P, ROOT, ERA_NAMES, CATALOGS  # noqa: E402
from lexicon import PHYS, OLD_FRAMES, TECH_FRAMES, ENTITY_F, VOICE_F  # noqa: E402

d = json.load(open(os.path.join(P, 'drift.json')))
t = json.load(open(os.path.join(P, 'tech.json')))
tr = json.load(open(os.path.join(P, 'tree.json')))
L = []
w = L.append


def ci(o, k=2):
    if o is None or o[0] != o[0]:
        return 'n/a'
    hi = o[2] if math.isfinite(o[2]) else float('inf')
    return f'{o[0]:.{k}f} ({o[1]:.{k}f}-{hi:.{k}f})'


def pct(o):
    return f'{100 * o[0]:.1f} ({100 * o[1]:.1f}-{100 * o[2]:.1f})'


w('# Deep-time descriptor tables (generated by omega/deeptime/report.py)\n')
w('## T1. Records per catalog and era (all records, natural-named included)\n')
w('| catalog | ' + ' | '.join(e.split()[0] for e in ERA_NAMES) + ' |')
w('|---|' + '---|' * len(ERA_NAMES))
for c, row in d['counts'].items():
    w(f'| {c} | ' + ' | '.join(str(row[e]) for e in ERA_NAMES) + ' |')
w('\nEra codes: ' + '; '.join(ERA_NAMES) + '.\n')

w('## T2. Before 1800 vs after 1947, unexplained reports, within catalog\n')
a = d['ancient_vs_modern_adjusted_OR']
w(f"Length-adjusted OR: logistic regression with catalog fixed effects and log(words); catalogs with records in both "
  f"periods: {', '.join(a['catalogs'])}; n = {a['n_ancient']} before 1800, {a['n_modern']} after 1947. "
  f"MH = Mantel-Haenszel OR stratified by catalog. Natural = reports that name a comet, meteor, aurora, halo, etc. "
  f"(n = {d['n_ancient_modern']['natural'][0]} / {d['n_ancient_modern']['natural'][1]}). OR > 1 = more common before 1800.\n")
w('| feature | length-adjusted OR (95% CI) | MH OR unexplained | MH OR natural |')
w('|---|---|---|---|')
for f in PHYS + OLD_FRAMES + TECH_FRAMES + ENTITY_F + VOICE_F:
    w(f"| {f} | {ci(a['OR'].get(f))} | {ci(d['ancient_vs_modern_MH_OR']['unexplained'].get(f))} | {ci(d['ancient_vs_modern_MH_OR']['natural'].get(f))} |")
pc = d['drift_pattern_corr_unexpl_vs_natural']
w(f"\nAcross {len(pc['features'])} features, log-OR pattern correlation unexplained vs natural r = {pc['pearson_r']:.2f}; "
  f"mean |log OR| {pc['mean_abs_logOR_unexpl']:.2f} (unexplained) vs {pc['mean_abs_logOR_natural']:.2f} (natural).\n")

w('## T3. Catalog-standardised prevalence (%) by era, unexplained reports\n')
std = d['standardised_prevalence']
eras = [e for e in ERA_NAMES if e in std['disc']]
w('| feature | ' + ' | '.join(e.split()[0] for e in eras) + ' | era LR chi2 |')
w('|---|' + '---|' * (len(eras) + 1))
for f in PHYS + OLD_FRAMES + TECH_FRAMES + ENTITY_F:
    w(f'| {f} | ' + ' | '.join(f'{100 * std[f][e]:.1f}' for e in eras) + f" | {d['era_LR_chi2'][f]:.0f} |")
w(f"\nLR chi2 df = {d['era_LR_df']}.\n")

w(f"## T4. Era boundaries inside one compiler (n = {d['era_boundaries']['n_per_era']} per era, 200 draws)\n")
w('Divergence between adjacent eras divided by the split-half null at the same n; p>null = share of draws above the null 95th percentile.\n')
w('| catalog | boundary | x noise | p>null |')
w('|---|---|---|---|')
for c, res in d['era_boundaries']['by_catalog'].items():
    for x in res:
        w(f"| {c} | {x['pair'][0].split()[0]} -> {x['pair'][1].split()[0]} | {x['excess']:.2f} | {x['p_gt_null']:.2f} |")

ca = d['compiler_agreement']
w(f"\n## T5. Same event, different catalogs (firm links: same full date, word overlap >= 0.2; {ca['n_pairs']} pairs)\n")
w('| feature | pairs with feature in either | in both | kappa |')
w('|---|---|---|---|')
for f, v in sorted(ca['per_feature'].items(), key=lambda kv: -(kv[1]['kappa'] if kv[1]['kappa'] == kv[1]['kappa'] else -9)):
    if v['any'] >= 20:
        w(f"| {f} | {v['any']} | {v['both']} | {v['kappa']:.2f} |")
w('\nCatalog pairs: ' + ', '.join(f'{k} {v}' for k, v in sorted(ca['catalog_pairs'].items(), key=lambda kv: -kv[1])) + '.\n')
lp = d['llm_paraphrase_check']
w(f"## T6. LLM paraphrase (Wonders in the Sky, ancient.json) vs other catalogs on {lp['n_events']} shared events\n")
w('| feature | events where WITS has it | mean over other catalogs |')
w('|---|---|---|')
for f in sorted(lp['wits'], key=lambda f: -lp['wits'][f]):
    if lp['wits'][f] + lp['others_mean'].get(f, 0) >= 8:
        w(f"| {f} | {lp['wits'][f]} | {lp['others_mean'].get(f, 0):.1f} |")
o = d['obsequens_vs_catalog_antiquity']
w(f"\n## T7. Obsequens (191-12 BC primary text, n = {o['n'][0]}) vs catalog records AD 34-499 (n = {o['n'][1]}), % with feature\n")
w('| feature | Obsequens | catalogs |')
w('|---|---|---|')
for f, x, y in zip(o['feats'], o['obsequens'], o['catalogs']):
    if x + y >= 0.03:
        w(f'| {f} | {100 * x:.0f} | {100 * y:.0f} |')

w('\n## T8. Technology words vs the year the technology appeared\n')
w('Rate per 1,000 unexplained records, 50 years before vs 50 years after t0; change point = maximum-likelihood single step '
  '(90% parametric-bootstrap interval). Pre-t0 uses classified automatically (see tech.py).\n')
w('| frame | t0 | event | catalogs 50y before -> after | catalog change point | NUFORC change point | pre-t0 uses (catalogs) |')
w('|---|---|---|---|---|---|---|')
for f, x in t['A_tech_frames'].items():
    c = x['catalogs']; wv = c['window50']; nu = x.get('nuforc', {})
    w(f"| {f} | {x['t0']} | {x['event']} | {wv['per1000_before']:.1f} -> {wv['per1000_after']:.1f} | {c.get('change_point')} {c.get('change_point_90ci') or ''} | "
      f"{nu.get('change_point', '')} {nu.get('change_point_90ci') or ''} | {', '.join(f'{k}: {v}' for k, v in x['pre_t0_classes'].items())} |")
C = t['C_newest_tech_share']
w(f"\nNewest-technology share, vehicle-framed reports 1700-1946 (n = {C['n']}): observed {100 * C['observed']:.1f}%, "
  f"year-shuffled null {100 * C['null_mean']:.1f}% (97.5th pct {100 * C['null_p975']:.1f}%), p = {C['p']:.4f}.\n")
w('| period | n | ' + ' | '.join(k for k in next(iter(C['by_period'].values())) if k != 'n') + ' |')
w('|---|---|' + '---|' * (len(next(iter(C['by_period'].values()))) - 1))
for k, v in C['by_period'].items():
    w(f'| {k} | {v["n"]} | ' + ' | '.join(str(v[f]) for f in v if f != 'n') + ' |')

w('\n## T9. Shapes by decade (% of reports, Wilson 95% CI), Hatch (one compiler) and NUFORC (witness text)\n')
for src, tab in t['B_congruent_by_decade'].items():
    fs = [f for f in next(iter(tab.values())) if f != 'n']
    w(f'**{src}**\n')
    w('| decade | n | ' + ' | '.join(fs) + ' |')
    w('|---|---|' + '---|' * len(fs))
    for dec, v in tab.items():
        w(f"| {dec}s | {v['n']} | " + ' | '.join(f'{100 * v[f][0]:.1f}' for f in fs) + ' |')
    w('')

Dd = t['D_primitives_vs_identified']
w(f"## T10. GEIPAN: share identified (A+B) and unexplained (D) among reports with each feature (base: A+B {100 * Dd['base']['AB']:.0f}%, "
  f"D {100 * Dd['base']['D']:.1f}%, n = {Dd['base']['n']})\n")
w('| feature | n | A+B % (95% CI) | D % (95% CI) |')
w('|---|---|---|---|')
for f, v in Dd['per_feature'].items():
    if v['n'] >= 20:
        w(f"| {f} | {v['n']} | {pct(v['AB'])} | {pct(v['D'])} |")

E = t['E_ancient_astronaut']
w('\n## T11. Ancient-astronaut predictions\n')
a1 = E['AA1_structured_craft_close']
w(f"AA1 structured craft seen close (shape term + landing or occupants): before 1800 {pct(a1['pre1800'])}%, after 1947 "
  f"{pct(a1['post1947'])}%, within-catalog MH OR {ci(a1['MH_OR_within_catalog'])}; before 1800 without the LLM-paraphrased "
  f"catalogs {pct(a1['pre1800_excluding_llm'])}%.\n")
w('AA2 occupant reports: how they are framed, by era\n')
w('| era | n | religious or creature % | space/alien % | airship/aircraft/balloon % |')
w('|---|---|---|---|---|')
for e, v in E['AA2_occupant_framing']['by_era'].items():
    w(f"| {e} | {v['n']} | {100 * v.get('religious_or_creature', 0) / v['n']:.1f} | {100 * v.get('space_alien', 0) / v['n']:.1f} | "
      f"{100 * v.get('airship_aircraft', 0) / v['n']:.1f} |")
a3 = E['AA3_primary_text']
w(f"\nAA3 Obsequens: {a3['n']} sky clauses, {a3['any_craft_shape']} with a craft-shape term, {a3['landing_or_occupant']} with a landing "
  f"or occupants; frames {a3['frames']}.\n")
w(f"AA5 region of catalog records before 1500: {E['AA5_regions_pre1500']['counts']}.\n")

w('## T12. Description-population tree\n')
w(f"{len(tr['taxa'])} taxa, {len(tr['characters'])} characters. Blomberg's K (999 tip permutations):\n")
w('| trait | K | p | null median |')
w('|---|---|---|---|')
for k, v in tr['blomberg_K'].items():
    w(f"| {k} | {v['K']:.2f} | {v['p']:.3f} | {v['null_median']:.2f} |")
m = tr['MRM']
w(f"\nMRM on distance matrices: R2 = {m['R2']:.3f} (p = {m['p_R2']:.3f}).\n")
w('| term | beta | p |')
w('|---|---|---|')
for k, v in m['terms'].items():
    w(f"| {k} | {v['beta']:.3f} | {v['p']:.3f} |")
dl = tr['delta']
w(f"\nDelta score (lower = more tree-like): {dl['observed']:.3f}; null with each character shuffled across taxa "
  f"{dl['null_mean']:.3f} (2.5th pct {dl['null_p025']:.3f}); p = {dl['p_lower']:.3f}.\n")
ns = tr['nearest_summary']
w(f"Nearest neighbour of each taxon: same compiler {100 * ns['same_compiler']:.0f}%, within 100 years {100 * ns['within_100y']:.0f}%.\n")
w('Bootstrap support >= 70% (200 replicates):\n')
for k, v in sorted(tr['bootstrap_support'].items(), key=lambda kv: -kv[1]):
    if v >= 0.7:
        w(f'- {100 * v:.0f}%: {k.replace("|", " ").replace("  ", " ")}')
w('')
w('Taxa: ' + ', '.join(f"{n} (n={v['n']})" for n, v in tr['taxa'].items()) + '.')
open(os.path.join(ROOT, 'omega', 'reports', 'deep_time_tables.md'), 'w').write('\n'.join(L) + '\n')
print('wrote omega/reports/deep_time_tables.md', len(L), 'lines')
