"""Builds omega/reports/craft_taxonomy_tables.md from the JSON outputs. Every number quoted in
craft_taxonomy.md comes from these tables."""
import json, os, gzip, numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
P = f'{ROOT}/data/processed/taxonomy'
OUT = f'{ROOT}/omega/reports/craft_taxonomy_tables.md'


def j(name):
    p = f'{P}/{name}'
    return json.load(open(p)) if os.path.exists(p) else None


def ci(d, k='RR'):
    return '%.2f (%.2f–%.2f)' % (d[k], d['lo'], d['hi'])


def bh(ps):
    ps = np.asarray(ps, float); m = len(ps); o = np.argsort(ps); q = np.empty(m); run = 1.0
    for rank, i in reversed(list(enumerate(o, 1))):
        run = min(run, ps[i] * m / rank); q[i] = run
    return q


def trend_status(t):
    if 'its_OR' not in t:
        return 'n/a (window too short)'
    if t['its_hi'] / max(t['its_lo'], 1e-12) > 20:
        return 'too noisy to adjust'
    same = np.sign(np.log(t['its_OR'])) == np.sign(t['logor'])
    if (t.get('its_placebo_pct_abs') or 0) >= 0.9 and same:
        return 'holds'
    return 'not separable from trend'


def main():
    L = []
    w = L.append
    w('# Craft taxonomy — tables (generated by `omega/taxonomy/report.py`)\n')
    S = j('stability.json')
    # ---------------- K selection + classes
    if S:
        w('## 1. Number of classes (latent class analysis)\n')
        w('Rule: largest K where every class re-appears (centred-profile r ≥ 0.7) in each of 3 random '
          'half-splits, mean of the minimum r ≥ 0.8. 12 restarts per fit. NUFORC selection on a fixed 40k subsample.\n')
        for src, m in S['models'].items():
            w(f'**{src}** (n = {m["n"]:,}) chose K = {m["K"]}\n')
            w('| K | BIC | min r in each half-split |')
            w('|---|---|---|')
            for s in m['selectk']:
                w('| %d | %.0f | %s |' % (s['K'], s['bic'], ', '.join('%.2f' % x for x in s['split_min_r_each'])))
            w('')
        w('## 2. The classes\n')
        for src, m in S['models'].items():
            w(f'**{src}**, K = {m["K"]}\n')
            w('| class | share | defining features (probability in class; shown if ≥ 20% and ≥ 1.3× the source average) |')
            w('|---|---|---|')
            for k in range(m['K']):
                w('| %d | %.1f%% | %s |' % (k, 100 * m['pi'][k], m['labels'][k]))
            w('')
        w('## 3. Stability across regions and eras\n')
        w('Each cell: correlation (centred profiles) between the class fitted on that subset and on all other '
          'records. Ceiling = same-size random subset of the other records (sampling noise only). '
          'Floor = the subset with each feature shuffled independently (co-occurrence destroyed); max of 3 shuffles, '
          'per class, in brackets. A class whose r does not clear its own floor is not evidence of co-occurring '
          'features: one-feature classes (e.g. "cigar 100%") are re-created from shuffled data.\n')
        for src, st in S['stability'].items():
            K = S['models'][src]['K']
            w(f'**{src}**\n')
            w('| subset | n | ' + ' | '.join(f'class {k}' for k in range(K)) + ' | ceiling (mean / min) |')
            w('|---|---|' + '---|' * K + '---|')
            for g, c in st.items():
                fl = c.get('floor_by_class', [float('nan')] * K)
                cells = ['%s%.2f (%.2f)' % ('**' if (r_ >= 0.7 and r_ > f_) else '', r_, f_) + ('**' if (r_ >= 0.7 and r_ > f_) else '')
                         for r_, f_ in zip(c['r_by_class'], fl)]
                w('| %s | %d | %s | %.2f / %.2f |' % (g, c.get('n_total', c['n']), ' | '.join(cells), c['ceiling_mean'], c['ceiling_min']))
            w('')
            w('Bold: r >= 0.7 and above that class\'s shuffled floor.')
            w('')
            w('Class shares by subset (full-source model):\n')
            w('| subset | ' + ' | '.join(f'class {k}' for k in range(K)) + ' |')
            w('|---|' + '---|' * K)
            for g, c in st.items():
                w('| %s | %s |' % (g, ' | '.join('%.1f%%' % (100 * x) for x in c['share'])))
            w('')
        DG = j('stability_diag.json')
        if DG:
            w('NUFORC, the one failed region (post-hoc diagnostic, `stability.py diag`): the K = 5 model fitted on '
              'US East and on all other regions, side by side.\n')
            w('| US East | all other regions |')
            w('|---|---|')
            for a, b in zip(DG['nuforc_us_east_k5']['US East'], DG['nuforc_us_east_k5']['rest']):
                w('| %.1f%%: %s | %.1f%%: %s |' % (100 * a['share'], a['label'], 100 * b['share'], b['label']))
            w('')
        if S.get('cross_source'):
            w('## 4. Do classes match across sources? (weakest test: coding depth differs by source)\n')
            for pair, rows in S['cross_source'].items():
                w(f'**{pair}**\n')
                w('| r | class A | class B |')
                w('|---|---|---|')
                for d in rows:
                    w('| %.2f | %d: %s | %d: %s |' % (d['r'], d['a'], d['a_label'], d['b'], d['b_label']))
                w('')
    # ---------------- stimuli
    G = j('geipan_d_vs_ab.json')
    if G:
        w('## 5. GEIPAN: what each shape turned out to be\n')
        w('| shape (witness text) | n | explained (A+B) | unexplained (D) | most common explanations |')
        w('|---|---|---|---|---|')
        for sh, d in G['by_shape'].items():
            w('| %s | %d | %.0f%% | %.1f%% | %s |' % (sh, d['n'], 100 * d['explained_share'], 100 * d['D_share'],
                                                   ', '.join('%s %d' % kv for kv in list(d['explained_as'].items())[:5])))
        w('')
        w('## 6. GEIPAN: do unexplained (D) cases describe different things from explained (A/B)?\n')
        w('n D = %d, n A/B = %d. Cross-validated AUC: features + text length %.3f; text length alone %.3f. '
          'Shuffled labels: mean %.3f (95th pct %.3f), p = %.3f. Features shuffled within text-length deciles: '
          'mean %.3f (95th pct %.3f), p = %.3f.\n' % (G['n_D'], G['n_AB'], G['cv_auc'], G['cv_auc_length_only'],
                                                      G['perm_null_auc_mean'], G['perm_null_auc_95'], G['perm_p'],
                                                      G['within_length_perm_auc_mean'], G['within_length_perm_auc_95'],
                                                      G['within_length_perm_p']))
        w('| feature | D | A/B | OR adjusted for text length (95% CI) | BH q |')
        w('|---|---|---|---|---|')
        for r in G['features'][:14]:
            w('| %s | %.1f%% | %.1f%% | %.2f (%.2f–%.2f) | %.3f |' % (r['feature'], 100 * r['D_rate'], 100 * r['AB_rate'],
                                                                   r['OR_len_adj'], r['lo'], r['hi'], r['q_BH']))
        w('')
    ST = j('stimuli.json')
    LAB = {src: m['labels'] for src, m in S['models'].items()} if S else {}   # one source of truth for class names
    if ST:
        w('## 7. What is inside the classes\n')
        g = ST['geipan']
        w('GEIPAN classes: D vs A/B across classes, Cramér V = %.3f, p = %.3g\n' % (g['D_vs_AB']['cramers_v'], g['D_vs_AB']['p']))
        w('| GEIPAN class | n | D share | explained as (top) |')
        w('|---|---|---|---|')
        for k, c in enumerate(g['classes']):
            w('| %d: %s | %d | %.1f%% | %s |' % (k, LAB.get('GEIPAN', g['labels'])[k], c['n'], 100 * c['D_share'],
                                                ', '.join('%s %d' % kv for kv in list(c['explained_family'].items())[:5])))
        w('')
        h = ST['hatch']
        flags = list(h['base'])
        w('Hatch classes: compiler flags (MID likely misidentification, HOX hoax suspected, HQO high-quality observer, '
          'RDR radar, PHT photo, EME electromagnetic effects, TRC traces, MIL military observer, NUC nuclear-related, '
          'LND landing, OID small humanoid)\n')
        w('| class | n | strangeness | credibility | ' + ' | '.join(flags) + ' |')
        w('|---|---|---|---|' + '---|' * len(flags))
        w('| all | | | | ' + ' | '.join('%.0f%%' % (100 * h['base'][f]) for f in flags) + ' |')
        for k, c in enumerate(h['classes']):
            w('| %d: %s | %d | %.1f | %.1f | %s |' % (k, LAB.get('HATCH', h['labels'])[k], c['n'], c['strangeness'] or -1, c['credibility'] or -1,
                                                     ' | '.join('%.0f%%' % (100 * c['flags'][f]) for f in flags)))
        w('')
        ek = ST.get('geipan_era_k2')
        if ek:
            w('GEIPAN two-class model fitted separately before and from 2010 (post-hoc diagnostic, added after the '
              '2010+ subset failed to replicate in section 3):\n')
            w('| era | n | class | share | defining features | D | explained as (top) |')
            w('|---|---|---|---|---|---|---|')
            for era, e in ek.items():
                for k, c in enumerate(e['classes']):
                    w('| %s | %d | %d | %.1f%% | %s | %d | %s |' % (era, e['n'], k, 100 * c['share'], c['label'],
                                                               c['gclass'].get('D', 0),
                                                               ', '.join('%s %d' % kv for kv in c['explained_as'].items())))
            w('')
        nu = ST['nuforc']
        w('NUFORC classes: share of one-line summaries naming a conventional object (Starlink, satellite, planet, '
          'plane, drone, balloon, lantern, flare...); all reports %.1f%%\n' % (100 * nu['base']))
        w('| class | n | names a conventional object |')
        w('|---|---|---|')
        for k, c in enumerate(nu['classes']):
            w('| %d: %s | %d | %.1f%% |' % (k, LAB.get('NUFORC', nu['labels'])[k], c['n'], 100 * c['names_explanation']))
        w('')
    # ---------------- drift
    DR = j('drift.json')
    if DR:
        w('## 8. Drift around dated events\n')
        w('Share after vs before (same-length windows); odds ratio, Wald 95%% CI. Placebo = fraction of other break dates '
          'with a smaller |log OR|. Trend-adjusted = segmented regression level change at the date net of the pre-trend '
          '(quasi-binomial), with its own placebo; "holds" means it beats 90%% of placebo dates in the same direction. '
          'Data: NUFORC reports posted within a year (n = %d), Hatch dated (n = %d), GEIPAN contemporaneous (n = %d).\n' % (
              DR['n']['nuforc_prompt'], DR['n']['hatch'], DR['n']['geipan']))
        w('| test | kind | break | window | before → after | OR (95% CI) | placebo pct | trend-adjusted OR (95% CI) | trend-adjusted |')
        w('|---|---|---|---|---|---|---|---|---|')
        for t in DR['tests']:
            if 'OR' not in t:
                w('| %s | | | | | insufficient data | | | |' % t['name']); continue
            its = '%.2f (%.2f–%.2f)' % (t['its_OR'], t['its_lo'], t['its_hi']) if 'its_OR' in t else '—'
            w('| %s | %s | %s | ±%d %s | %.2f%% → %.2f%% | %.2f (%.2f–%.2f) | %.2f | %s | %s |' % (
                t['name'], t['kind'], t['break_at'], t['window'], t['unit'] + 's', 100 * t['pre_share'], 100 * t['post_share'],
                t['OR'], t['lo'], t['hi'], t['placebo_pct_abs'] if t['placebo_pct_abs'] is not None else float('nan'),
                its, trend_status(t)))
        w('')
        if DR.get('nuforc_pre1990'):
            rp = DR['nuforc_pre1990']
            w('NUFORC events before 1990: %d reports, %d of them posted in 1995 or later, %d within a year of the event.\n' % (
                rp['n'], rp['posted_1995_or_later'], rp['posted_within_a_year']))
        gl = DR['geipan_lantern']
        w('GEIPAN orange ball/light cases explained as lanterns: before 2008 %d of %d; 2008 on %d of %d.\n' % (
            gl.get('pre-2008', [0, 0])[0], gl.get('pre-2008', [0, 0])[1], gl.get('2008+', [0, 0])[0], gl.get('2008+', [0, 0])[1]))
    # ---------------- geography
    GE = j('geo.json')
    if GE:
        w('## 9. Geography: NUFORC, contiguous US, against population (HRSL 2019)\n')
        w('Rate ratio (RR) per person, quasi-Poisson, adjusted for population-density decile and 4 longitude regions; '
          'reference ≥ 100 km from the nearest site of that type. "vs other reports": the same model with all reports in the '
          'cell as offset (does the class sit nearer the site than other reports do?). BH q over all class/shape × layer × band '
          'enrichment tests at that cell size. Layer counts: %s.\n' % ', '.join('%s %d' % kv for kv in GE['layer_counts'].items()))
        for key, title in (('nuforc_us', '0.05° cells (~5 km)'), ('nuforc_us_025', '0.25° cells (~25 km)')):
            g = GE.get(key)
            if not g:
                continue
            w(f'### {title}: {g["n_reports"]:,} reports in {g["n_cells"]:,} populated cells; {g["n_unplaced"]:,} unplaced\n')
            w('Crude: share of population vs share of reports within 25 km:\n')
            w('| site type | population | reports |')
            w('|---|---|---|')
            for k, d in g['crude_lt25km'].items():
                w('| %s | %.1f%% | %.1f%% |' % (k, 100 * d['pop_share_lt25'], 100 * d['report_share_lt25']))
            w('')
            tests = []
            for lay, res in g['layers'].items():
                for grp, d in res.items():
                    if d['vs_other_reports']:
                        for b, v in d['vs_other_reports'].items():
                            tests.append((lay, grp, b, v['p']))
            q = dict(zip([(a, b, c) for a, b, c, _ in tests], bh([t[3] for t in tests]))) if tests else {}
            for lay, res in g['layers'].items():
                w(f'**{lay}**\n')
                w('| group | n | per person 0–25 km | 25–50 km | 50–100 km | vs other reports 0–25 km | BH q |')
                w('|---|---|---|---|---|---|---|')
                for grp, d in res.items():
                    pc = d['per_capita']; en = d['vs_other_reports']
                    lab = grp
                    labs = LAB.get('NUFORC') or g.get('labels')
                    if grp.startswith('class') and labs:
                        k = int(grp[5:]); lab = '%s: %s' % (grp, labs[k][:70])
                    w('| %s | %d | %s | %s | %s | %s | %s |' % (lab, d['n'], ci(pc['0-25 km']), ci(pc['25-50 km']), ci(pc['50-100 km']),
                                                             ci(en['0-25 km']) if en else '—',
                                                             '%.3f' % q[(lay, grp, '0-25 km')] if en else '—'))
                w('')
            w('Joint model (all reports; airports, military airfields and nuclear plants < 25 km together): ' +
              '; '.join('%s %s' % (k, ci(v)) for k, v in g['joint_lt25km_ALL'].items()) + '\n')
            w('Terrain (per person, all reports; reference: < 300 m elevation, < 10 m relief, < 10 km from coast):\n')
            w('| covariate | band | RR (95% CI) |')
            w('|---|---|---|')
            for nm, res in g['terrain'].items():
                for b, v in res['ALL']['per_capita'].items():
                    w('| %s | %s | %s |' % (nm, b, ci(v)))
            w('')
            w('Terrain by class (vs other reports in the same cells; same reference bands):\n')
            labs = LAB.get('NUFORC') or g.get('labels') or []
            hdr = [(nm, b) for nm, res in g['terrain'].items() for b in res['ALL']['per_capita']]
            w('| class | ' + ' | '.join('%s %s' % hb for hb in hdr) + ' |')
            w('|---|' + '---|' * len(hdr))
            for grp in g['terrain']['elevation']:
                if not grp.startswith('class'):
                    continue
                k = int(grp[5:])
                cells = [ci(g['terrain'][nm][grp]['vs_other_reports'][b]) for nm, b in hdr]
                w('| %s | %s |' % ('%s: %s' % (grp, labs[k][:40]) if labs else grp, ' | '.join(cells)))
            w('')
            w('Per-person reporting by population-density decile (1 = sparsest, reference): ' +
              ', '.join('%.2f' % x for x in g['density_decile_RR']) + '\n')
        H = GE.get('hatch_world')
        if H and H.get('classes'):
            w('## 10. Hatch, worldwide: each class vs all other Hatch reports\n')
            w('Logistic, adjusted for %s (no world population layer here, so classes are compared with other reports, '
              'not with people). Reactors counted only in years they operated. Crude = region only: reactors came on line '
              'while the class mix changed, so the crude OR mixes in the era. Sensitivity: without the two triangle waves '
              'near reactors (%s), and one record per class x 0.5 degree cell x year (n = %d). BH q over the 14 adjusted '
              'tests. Base rates: %s\n' % (H.get('adjust', 'region'),
                                          '; '.join('%s: %d records, %d within 50 km of a reactor' % (nm, w_['n'], w_['near_nuclear'])
                                                    for nm, w_ in H.get('waves', {}).items()),
                                          H.get('n_dedup', 0), ', '.join('%s %.1f%%' % (k, 100 * v) for k, v in H['near_rate'].items())))
            tests = [(k, nm, d[nm]['p']) for k, d in H['classes'].items() for nm in ('military_airfield<=50km', 'nuclear_plant_operating<=50km')]
            qh = dict(zip([(a, b) for a, b, _ in tests], bh([t[2] for t in tests])))
            for nm, title in (('military_airfield<=50km', 'military airfield (name proxy) within 50 km'),
                              ('nuclear_plant_operating<=50km', 'operating nuclear plant within 50 km')):
                w(f'**{title}**\n')
                w('| class | n | OR adjusted (95% CI) | BH q | crude | without the waves | one per cell-year |')
                w('|---|---|---|---|---|---|---|')
                for k, d in H['classes'].items():
                    hl = LAB.get('HATCH'); e = d[nm]
                    w('| %s | %d | %s | %.3f | %.2f | %s | %s |' % ('%s: %s' % (k, hl[int(k[5:])]) if hl else k, d['n'], ci(e, 'OR'),
                                                              qh[(k, nm)], e['crude_region_only']['OR'] if 'crude_region_only' in e else float('nan'),
                                                              ci(e['without_waves'], 'OR') if 'without_waves' in e else '—',
                                                              ci(e['dedup'], 'OR') if 'dedup' in e else '—'))
                w('')
            w('Hatch NUC flag (compiler: nuclear-facility related) by class: ' +
              ', '.join('%s %.1f%%' % (k, 100 * v) for k, v in H['nuc_code_rate_by_class'].items()) + '\n')
            w('Hatch "Locale" (the compiler\'s terrain field), lift over the all-report share:\n')
            locs = list(next(iter(H['locale'].values())).keys())
            w('| class | ' + ' | '.join(locs) + ' |')
            w('|---|' + '---|' * len(locs))
            for k, d in H['locale'].items():
                hl = LAB.get('HATCH')
                w('| %s | %s |' % ('%s: %s' % (k, hl[int(k[5:])][:40]) if hl else k, ' | '.join('%.2f' % d[l]['lift'] for l in locs)))
            w('')
        F_ = GE.get('geipan_fr')
        if F_:
            w('## 11. GEIPAN, France: unexplained (D) vs explained (A/B) near sites\n')
            w('Nuclear layer: GeoNuclearData reactors in France operating in the case year (%d reactor rows). '
              'Replaces the hand-entered 28-site layer of `geipan_phase123.py`.\n' % F_['n_sites'])
            w('Adjusted for %s.\n' % F_.get('adjust', 'nothing'))
            w('| site, radius | D near / all D | A/B near / all A/B | OR adjusted (95% CI) | crude OR |')
            w('|---|---|---|---|---|')
            for k, d in F_.items():
                if isinstance(d, dict) and 'OR' in d:
                    w('| %s | %d / %d | %d / %d | %s | %s |' % (k, d['D_near'], d['D_near'] + d['D_far'], d['AB_near'],
                                                              d['AB_near'] + d['AB_far'], ci(d, 'OR'),
                                                              '%.2f' % d['crude']['OR'] if 'crude' in d else '—'))
            w('')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', OUT, len(L), 'lines')


if __name__ == '__main__':
    main()
